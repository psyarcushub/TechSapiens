function hash(text: string): number {
  let h = 2166136261
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}

/** Ответ «ИИ» на вопрос: один и тот же вопрос даёт один и тот же ответ. */
export function fakeAiReply(question: string, replies: readonly string[] = DEFAULT_REPLIES): string {
  if (replies.length === 0) return 'Я задумался. Спросите ещё раз чуть позже.'
  return replies[hash(question.trim().toLowerCase()) % replies.length]
}

/** То же, но с паузой «на подумать», как у настоящего ИИ. */
export function askFakeAi(
  question: string,
  options: { delayMs?: number; replies?: readonly string[] } = {},
): Promise<string> {
  const delay = options.delayMs ?? 700 + (hash(question) % 900)
  return new Promise((resolve) => {
    setTimeout(() => resolve(fakeAiReply(question, options.replies)), delay)
  })
}
